x = int(input("Escreva um valor de número inteiro: "))
y = int(input("Escreva um valor de número inteiro: "))

m = x * y
d = x / y
e = x ** y
rd = x // y

print("O resultado da multiplicação é: ", m)
print("O resultado da divisão é: ", d)
print("O resultado da exponenciação é: ", e)
print("O resultado do resto da divisão é: ", rd)